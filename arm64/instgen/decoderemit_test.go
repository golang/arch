const proseZn = "Is the name of the source scalable vector register, encoded in the \"Zn\" field.\nbit range mappings:\nZn: [5:10)\n"

func TestSplitRows(t *testing.T) {
	type row = struct{ mask, value uint32 }
	// An unsplit encoding is one row.
	got := splitRows(xmlspec.IREncoding{Binary: 0x04200000, Mask: 0xff200000})
	if want := []row{{0xff200000, 0x04200000}}; len(got) != 1 || got[0] != want[0] {
		t.Errorf("unsplit: got %#x, want %#x", got, want)
	}
	// A split whose Go op covers size values 0, 1 and 2 is three rows, each with
	// the size field in its mask.
	got = splitRows(xmlspec.IREncoding{
		Binary: 0x04200000, Mask: 0xff200000,
		SplitLo: 22, SplitHi: 24, SplitValues: []uint32{0, 1, 2},
	})
	want := []row{{0xffe00000, 0x04200000}, {0xffe00000, 0x04600000}, {0xffe00000, 0x04a00000}}
	if len(got) != len(want) {
		t.Fatalf("split: got %#x, want %#x", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("split row %d: got %#x, want %#x", i, got[i], want[i])
		}
	}
}

func regOperand(name, prose string) xmlspec.IROperand {
	return xmlspec.IROperand{
		Name: name, Typ: "AC_ZREG",
		Elems: []xmlspec.IRElement{{Symbol: name, TextExpWithRanges: prose, IsZ: true}},
	}
}

// movprfx is a form with two vector register operands and no variable
// arrangement.
func movprfx() xmlspec.IREncoding {
	return xmlspec.IREncoding{
		Asm: "MOVPRFX  <Zd>, <Zn>", GoOp: "AZMOVPRFX",
		Binary: 0x0420bc00, Mask: 0xfffffc00,
		// instgen stores operands in Go order: sources first, destination last.
		Operands: []xmlspec.IROperand{
			{Name: "MOVPRFX"},
			regOperand("<Zn>", proseZn),
			regOperand("<Zd>", proseZd),
		},
	}
}

func TestRender(t *testing.T) {
	g := &gen{
		syms: newSymtab(),
		dIdx: map[string]int{}, aIdx: map[string]int{}, lIdx: map[string]int{},
		oIdx: map[string]int{}, reasons: map[string]int{},
	}
	g.form(movprfx())
	if g.skippedForms != 0 {
		t.Fatalf("form skipped: %v", g.reasons)
	}
	if len(g.forms) != 1 || len(g.descs) != 2 || len(g.args) != 2 || len(g.lists) != 1 || len(g.ops) != 1 {
		t.Fatalf("got %d forms, %d descs, %d args, %d lists, %d ops; want 1, 2, 2, 1, 1",
			len(g.forms), len(g.descs), len(g.args), len(g.lists), len(g.ops))
	}
	// Inst.Args is in ARM order: destination first.
	if got, want := g.lists[0], []int{1, 0}; len(got) != 2 || got[0] != want[0] || got[1] != want[1] {
		t.Errorf("arg list = %v, want %v (Zd then Zn)", got, want)
	}

	src, err := g.render()
	if err != nil {
		t.Fatalf("generated file does not parse: %v", err)
	}
	text := string(src)
	for _, want := range []string{
		"// Code generated by 'go run golang.org/x/arch/arm64/instgen -decoder=sve_gen.go'. DO NOT EDIT.",
		"package arm64asm",
		"var sveOpARM = []string{\n\t\"MOVPRFX\",\n}",
		"var sveOpGo = []string{\n\t\"ZMOVPRFX\",\n}",
		"{role: roleReg, fields: []sveField{{5, 5}}, regfile: rfZ, fixed: -1}",
		"{role: roleReg, fields: []sveField{{0, 5}}, regfile: rfZ, fixed: -1}",
		"\t// MOVPRFX  <Zd>, <Zn>\n\t{mask: 0xfffffc00, value: 0x0420bc00, op: 0, args: 0},\n",
		// MOVPRFX has bits 31:25 = 0000010, so only value 2 is in the gate.
		"sveGateLo uint64 = 0x0000000000000004",
		"sveGateHi uint64 = 0x0000000000000000",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("generated file lacks %q:\n%s", want, text)
		}
	}
	// sveOpBase belongs to the runtime, and the tables are slices.
	for _, bad := range []string{"sveOpBase", "[...]", "zr:"} {
		if strings.Contains(text, bad) {
			t.Errorf("generated file contains %q", bad)
		}
	}
}

// More specific masks come first, so that the first match in a linear scan wins.
// A form that the generator cannot describe is an error, not a smaller table.
func TestSkippedFormIsAnError(t *testing.T) {
	g := &gen{
		syms: newSymtab(),
		dIdx: map[string]int{}, aIdx: map[string]int{}, lIdx: map[string]int{},
		oIdx: map[string]int{}, reasons: map[string]int{},
	}
	g.form(movprfx())
	if err := g.err(); err != nil {
		t.Fatalf("a form that can be described is an error: %v", err)
	}
	novel := movprfx()
	novel.Operands[1].Typ = "AC_NOVEL_CLASS"
	g.form(novel)
	err := g.err()
	if err == nil {
		t.Fatal("a form with an unknown operand class is not an error")
	}
	if !strings.Contains(err.Error(), "AC_NOVEL_CLASS") {
		t.Errorf("the error does not name the class: %v", err)
	}
}

// The tables that are checked in are what instgen writes for the ARM XML. This
// is the only test that notices a change to the generator or to a table that
// the other does not. Run it with -i naming the XML directory.
func TestDecoderTablesAreCurrent(t *testing.T) {
	if *input == "" {
		t.Skip("-i names no ARM XML directory, so the checked-in tables are not compared with the generator's output")
	}
	insts := xmlspec.ParseXMLFiles(*input)
	xmlspec.ProcessXMLFiles(insts)
	out := filepath.Join(t.TempDir(), "sve_gen.go")
	GenerateDecoder(insts, out)
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	want, err := os.ReadFile(filepath.Join("..", "arm64asm", "sve_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("arm64asm/sve_gen.go is not what instgen -decoder writes (%d bytes, want %d): regenerate it", len(want), len(got))
	}
}

var updateSample = flag.Bool("update-sample", false, "rewrite arm64asm's sve_sample_gen_test.go")

// TestSampleDecoderTables generates the decoder tables for xmlspec's test data,
// the unpredicated SVE ADD, and compares them with arm64asm's
// sve_sample_gen_test.go. arm64asm's TestSVESampleTables decodes with that file,
// so the two tests together take one instruction from the XML to its disassembly.
func TestSampleDecoderTables(t *testing.T) {
	insts := xmlspec.ParseXMLFiles(filepath.Join("xmlspec", "testdata"))
	xmlspec.ProcessXMLFiles(insts)
	out := filepath.Join(t.TempDir(), "sve_sample_gen_test.go")
	generateDecoder(insts, out, true)
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join("..", "arm64asm", "sve_sample_gen_test.go")
	if *updateSample {
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("%s is not what the generator writes for xmlspec/testdata: rerun this test with -update-sample", path)
	}
}

func TestRenderOrdersFormsByMask(t *testing.T) {
	g := &gen{
		syms: newSymtab(),
		dIdx: map[string]int{}, aIdx: map[string]int{}, lIdx: map[string]int{},
		oIdx: map[string]int{}, reasons: map[string]int{},
	}
	wide, narrow := movprfx(), movprfx()
	wide.Mask, wide.Binary = 0xfffff800, 0x0420b800
	narrow.GoOp, narrow.Asm = "AZMOVPRFX2", "MOVPRFX2  <Zd>, <Zn>"
	g.form(wide)
	g.form(narrow)
	src, err := g.render()
	if err != nil {
		t.Fatal(err)
	}
	text := string(src)
	i, j := strings.Index(text, "mask: 0xfffffc00"), strings.Index(text, "mask: 0xfffff800")
	if i < 0 || j < 0 || i > j {
		t.Errorf("forms are not ordered most specific mask first (positions %d, %d):\n%s", i, j, text)
	}
}

func TestGateBitmap(t *testing.T) {
	forms := []dForm{
		{Mask: 0xfe000000, Value: 0x04000000}, // bits 31:25 pinned to 2
		{Mask: 0xfe000000, Value: 0xa0000000}, // pinned to 0x50, in the high word
		{Mask: 0xfe000000, Value: 0xfe000000}, // pinned to 0x7f, the top bit of the high word
		{Mask: 0xf8000000, Value: 0x08000000}, // bits 31:27 pinned to 00001, bits 26:25 free: values 4 to 7
	}
	lo, hi, n := gateBitmap(forms)
	wantLo := uint64(1<<2 | 0xf<<4) // value 2, and 4 to 7
	wantHi := uint64(1<<(0x50-64) | 1<<(0x7f-64))
	if lo != wantLo || hi != wantHi || n != 7 {
		t.Errorf("gateBitmap = %#x, %#x, %d; want %#x, %#x, 7", lo, hi, n, wantLo, wantHi)
	}
	if lo, hi, n := gateBitmap(nil); lo != 0 || hi != 0 || n != 0 {
		t.Errorf("gateBitmap(nil) = %#x, %#x, %d; want zeros", lo, hi, n)
	}
}
